# Builds src/smart/spMap.ts from the São Paulo districts GeoJSON
# (github.com/codigourbano/distritos-sp).
# usage: python3 scripts/sp-map.py distritos-sp.geojson src/smart/spMap.ts
import json, math, sys
from shapely.geometry import shape
from shapely.ops import unary_union

W = 1000
feats = json.load(open(sys.argv[1]))["features"]
geoms = [shape(f["geometry"]) for f in feats]
names = [f["properties"]["ds_nome"] for f in feats]
city = unary_union(geoms)
minx, miny, maxx, maxy = city.bounds
kx = math.cos(math.radians((miny + maxy) / 2))
scale = W / ((maxx - minx) * kx)
H = round((maxy - miny) * scale)


def pt(x, y):
    return ((x - minx) * kx * scale, (maxy - y) * scale)


def path(g, tol):
    g = g.simplify(tol)
    polys = g.geoms if g.geom_type == "MultiPolygon" else [g]
    out = []
    for p in polys:
        for ring in [p.exterior]:
            xy = [pt(x, y) for x, y in ring.coords]
            out.append("M" + "L".join(f"{x:.0f} {y:.0f}" for x, y in xy) + "Z")
    return "".join(out)


districts = [path(g, 0.0012) for g in geoms]
outline = path(city, 0.0006)
centers = {}
for n, g in zip(names, geoms):
    c = g.representative_point()
    x, y = pt(c.x, c.y)
    centers[n] = [round(x), round(y)]

# Camera dots: denser toward the centre (Sé), sorted outward so they can
# light up as a ripple.
import random
random.seed(4)
cx, cy = centers["SE"]
cams = []
while len(cams) < 170:
    x, y = random.uniform(0, W), random.uniform(0, H)
    d = math.hypot(x - cx, y - cy)
    if random.random() > 0.15 + 0.85 * math.exp(-d / 260):
        continue
    lon = x / (kx * scale) + minx
    lat = maxy - y / scale
    if city.contains(shape({"type": "Point", "coordinates": [lon, lat]})):
        cams.append((round(x), round(y), d))
cams.sort(key=lambda c: c[2])

with open(sys.argv[2], "w") as f:
    f.write("// Generated by scripts/sp-map.py from the São Paulo districts GeoJSON.\n")
    f.write(f"export const SP_W = {W};\nexport const SP_H = {H};\n")
    f.write(f"export const spOutline = {json.dumps(outline)};\n")
    f.write("export const spDistricts: string[] = " + json.dumps(districts) + ";\n")
    f.write("export const spCameras: [number, number][] = " + json.dumps([[x, y] for x, y, _ in cams]) + ";\n")
    f.write("export const spCenters: Record<string, [number, number]> = " + json.dumps(centers, ensure_ascii=False) + ";\n")
print(W, H, len(districts), sum(len(d) for d in districts) + len(outline))
